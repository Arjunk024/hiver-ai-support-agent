import pandas as pd
from pathlib import Path

INPUT = Path("data/processed/spotify_clean.csv")
OUTPUT = Path("data/processed/evaluation/golden_test_cases_200.csv")

df = pd.read_csv(INPUT)

df = df[df["customer_text"].notna()].copy()
df["customer_text"] = df["customer_text"].astype(str).str.strip()
df = df[df["customer_text"] != ""]


def suggest_intent(text):
    text = str(text).lower()

    security_keywords = [
        "hacked", "hack", "stolen", "compromised",
        "unauthorized", "fraud", "payment information",
        "payment details", "card information", "card details",
        "debit card", "credit card", "used my card",
        "card was used", "someone used my card",
        "unknown payment", "unauthorized payment",
        "unauthorized charge", "don't recognize this charge",
        "charged without permission"
    ]

    login_keywords = [
        "can't login", "cannot login", "can't log in",
        "cannot log in", "login", "log in", "sign in",
        "signin", "password", "forgot my password"
    ]

    playback_keywords = [
        "buffer", "buffering", "won't play",
        "not playing", "stopping", "stops playing",
        "stopping after", "pausing", "pause",
        "skipping", "skip songs", "playback"
    ]

    playlist_keywords = [
        "playlist", "song missing", "songs missing",
        "songs disappeared", "playlist disappeared",
        "add song", "remove song"
    ]

    subscription_keywords = [
        "premium", "subscription", "family plan",
        "student plan", "student discount", "premium account"
    ]

    if any(k in text for k in security_keywords):
        return "security"

    if any(k in text for k in login_keywords):
        return "account_login"

    if any(k in text for k in playback_keywords):
        return "playback"

    if any(k in text for k in playlist_keywords):
        return "playlist"

    if any(k in text for k in subscription_keywords):
        return "subscription"

    return "general"


df["suggested_intent"] = df["customer_text"].apply(suggest_intent)

TARGET_COUNTS = {
    "general": 50,
    "subscription": 35,
    "playlist": 30,
    "account_login": 30,
    "security": 25,
    "playback": 30,
}

samples = []

for intent, count in TARGET_COUNTS.items():
    candidates = df[df["suggested_intent"] == intent]

    if len(candidates) < count:
        raise ValueError(
            f"Not enough examples for {intent}: "
            f"needed {count}, found {len(candidates)}"
        )

    samples.append(
        candidates.sample(n=count, random_state=42)
    )

golden = pd.concat(samples, ignore_index=True)

# Shuffle the final evaluation set
golden = golden.sample(frac=1, random_state=42).reset_index(drop=True)

golden.insert(0, "case_id", range(1, len(golden) + 1))

# IMPORTANT:
# suggested_intent is only a draft generated by our rules.
# gold_intent must be human-confirmed.
golden["gold_intent"] = ""

golden = golden[
    [
        "case_id",
        "customer_text",
        "suggested_intent",
        "gold_intent",
        "support_text"
    ]
]

OUTPUT.parent.mkdir(parents=True, exist_ok=True)
golden.to_csv(OUTPUT, index=False)

print("=" * 60)
print("STRATIFIED GOLDEN SET CREATED")
print("=" * 60)
print("Rows:", len(golden))
print()
print("Suggested distribution:")
print(golden["suggested_intent"].value_counts())
print()
print("Output:")
print(OUTPUT)
print()
print("IMPORTANT:")
print("suggested_intent = draft label")
print("gold_intent      = HUMAN-CONFIRMED label")
print("=" * 60)